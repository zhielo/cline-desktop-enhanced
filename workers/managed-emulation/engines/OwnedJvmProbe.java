import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.Set;

/** Diagnostic only: fixed public JDK operations, no emulator or JNI dependency. */
public final class OwnedJvmProbe {
    public static void main(String[] arguments) throws Exception {
        if (arguments.length != 0) throw new IllegalArgumentException("No probe arguments");
        if (Set.of("Cipher", "KeyStore", "MessageDigest", "Signature").size() != 4)
            throw new IllegalStateException("Owned immutable set failed");
        byte[] actual = MessageDigest.getInstance("SHA-256")
            .digest("abc".getBytes(StandardCharsets.US_ASCII));
        byte[] expected = new byte[] {
            (byte)0xba, 0x78, 0x16, (byte)0xbf, (byte)0x8f, 0x01, (byte)0xcf, (byte)0xea,
            0x41, 0x41, 0x40, (byte)0xde, 0x5d, (byte)0xae, 0x22, 0x23,
            (byte)0xb0, 0x03, 0x61, (byte)0xa3, (byte)0x96, 0x17, 0x7a, (byte)0x9c,
            (byte)0xb4, 0x10, (byte)0xff, 0x61, (byte)0xf2, 0x00, 0x15, (byte)0xad
        };
        if (!MessageDigest.isEqual(actual, expected))
            throw new IllegalStateException("Owned digest vector failed");
        byte[] random = new byte[32];
        new SecureRandom().nextBytes(random);
        Arrays.fill(random, (byte)0);
        // Exact path generated by the JDK inside this process's fresh private
        // tmpdir, never a caller-selected file. No random bytes/path in output.
        File temporary = File.createTempFile("cline-owned-jvm-", ".tmp");
        Files.delete(temporary.toPath());
        System.out.println("CLINE_MANAGED_OWNED_JVM_PROBE_V1 passed");
    }
}
